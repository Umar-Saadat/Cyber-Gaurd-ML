import streamlit as st

st.set_page_config(page_title="About Project - CyberGuard ML", page_icon="📖", layout="wide")

st.title("📖 About CyberGuard ML")
st.markdown("Academic Semester Project for **Machine Learning Fundamentals** (BS Artificial Intelligence).")

st.divider()

col1, col2 = st.columns([2, 1])

with col1:
    st.subheader("1. Project Motivation & Problem Statement")
    st.markdown("""
    Modern cyber threats cause billions of dollars in damage annually through distributed denial-of-service (DDoS),
    brute-force password penetration, port scanning reconnaissance, and automated bot infections.
    
    Traditional firewalls and rule-based intrusion detection systems (IDS) rely heavily on known static signatures.
    When an attacker slightly mutates their packet structure or alters payload timing, signature engines fail.
    
    **CyberGuard ML** leverages statistical machine learning on bi-directional network flow attributes
    (generated by CICFlowMeter) to identify anomalous behavioral patterns without requiring hardcoded signatures.
    """)

    st.subheader("2. Classification Hierarchy & Regression Architecture")
    st.markdown("""
    * **Level 1 (Binary Gatekeeper):** Rapidly screens incoming traffic into `BENIGN` or `ATTACK` with a probability confidence score (1–100%).
    * **Level 2 (Attack Specialist):** When traffic triggers the alarm at Level 1, it passes into a multiclass model that pinpoints the specific vector (e.g. `DDoS`, `PortScan`, `Bot`, `Patator`, `Web Attack`) along with an **Attack Type Confidence Score (1–100%)** directly obtained from the classifier's `predict_proba()` method.
    * **Level 3 (Continuous Flow Regression):** Simultaneously predicts continuous numerical flow characteristics (such as `Flow Duration` in microseconds or `Flow Bytes/s`). This models connection behavior and enables network operators to anticipate session duration and bandwidth consumption.
    """)

    st.subheader("3. Dataset Source: CICIDS2017")
    st.markdown("""
    Published by the **Canadian Institute for Cybersecurity (CIC)**, University of New Brunswick:
    * Captures realistic network traffic across 5 consecutive days (Monday through Friday).
    * Contains over 80 extracted statistical flow features including packet length moments, inter-arrival times (IAT), flag frequencies, and subflow totals.
    * Real-world traffic anomalies: includes protocol edge cases, zero-duration flows, infinite byte rates, and extreme class imbalance.
    """)

with col2:
    st.subheader("4. Evaluated Algorithms")
    st.markdown("""
    **Classification:**
    1. **Logistic Regression:** Linear decision boundary; rapid inference benchmark.
    2. **K-Nearest Neighbors (KNN):** Instance-based distance classifier.
    3. **Decision Tree:** Interpretable hierarchical tree splits.
    4. **Random Forest:** Ensemble of decorrelated decision trees.
    5. **SVM:** Optimal margin classifier.

    **Regression:**
    1. **Linear Regression:** Baseline continuous line fit.
    2. **Ridge Regression:** L2-regularized linear model.
    3. **Decision Tree Regressor:** Non-linear step regression.
    4. **Random Forest Regressor:** Multi-tree regression ensemble.
    """)

    st.subheader("5. Key Evaluation Metrics")
    st.markdown("""
    **Classification Metrics:**
    * **Accuracy & F1-Score:** Harmonic balance of classification precision and recall.
    * **Confidence Score (1–100%):** True posterior class probability $P(Y=k|X)$ from `predict_proba()`.

    **Regression Metrics:**
    * **MAE (Mean Absolute Error):** Average magnitude of absolute error.
    * **MSE & RMSE:** Penalizes large outlier errors heavily.
    * **R² (Coefficient of Determination):** Proportion of variance explained by model (1.0 = perfect fit).
    """)

